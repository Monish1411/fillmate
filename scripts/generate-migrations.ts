/**
 * Emits the PostgreSQL migration from the same schema definition the runtime
 * uses, so the two can never drift.
 *
 *   npm run gen:migrations
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { TABLES, renderCreateTable, renderIndexes } from "../lib/db/schema";

const OUT_DIR = path.join(process.cwd(), "supabase", "migrations");

const HEADER = `-- =============================================================================
-- FillMate - core schema (PostgreSQL / Supabase)
--
-- Generated from lib/db/schema.ts by npm run gen:migrations.
-- Do not edit by hand: edit the schema definition and regenerate.
--
-- Conventions
--   * ids are UUIDs generated by the application (gen_random_uuid() as default)
--   * every timestamp is timestamptz and stored in UTC
--   * JSON payloads are jsonb
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS "pgcrypto";
CREATE EXTENSION IF NOT EXISTS "pg_trgm";
`;

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  const statements: string[] = [HEADER];

  for (const table of TABLES) {
    statements.push(`\n-- ${table.name}\n${renderCreateTable(table, "postgres")}`);
    for (const index of renderIndexes(table, "postgres")) {
      statements.push(index);
    }
  }

  // uuid defaults so direct SQL inserts also work
  for (const table of TABLES) {
    statements.push(
      `ALTER TABLE "${table.name}" ALTER COLUMN "id" SET DEFAULT gen_random_uuid()::text;`,
    );
  }

  statements.push(
    `\n-- Helpful trigram index for the admin activity search box.
CREATE INDEX IF NOT EXISTS ix_users_full_name_trgm
  ON "users" USING gin ("full_name" gin_trgm_ops);
CREATE INDEX IF NOT EXISTS ix_rooms_number_trgm
  ON "rooms" USING gin ("number" gin_trgm_ops);

-- Keep updated_at honest even for direct SQL writes.
CREATE OR REPLACE FUNCTION fillmate_touch_updated_at() RETURNS trigger AS $$
BEGIN
  NEW."updated_at" = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_users_touch BEFORE UPDATE ON "users"
  FOR EACH ROW EXECUTE FUNCTION fillmate_touch_updated_at();
CREATE TRIGGER trg_rooms_touch BEFORE UPDATE ON "rooms"
  FOR EACH ROW EXECUTE FUNCTION fillmate_touch_updated_at();
CREATE TRIGGER trg_water_activities_touch BEFORE UPDATE ON "water_activities"
  FOR EACH ROW EXECUTE FUNCTION fillmate_touch_updated_at();`,
  );

  await writeFile(
    path.join(OUT_DIR, "0001_core_schema.sql"),
    statements.join("\n") + "\n",
    "utf8",
  );

  console.log(`[migrations] wrote ${TABLES.length} tables to supabase/migrations/0001_core_schema.sql`);
  process.exit(0);
}

main().catch((err) => {
  console.error("[migrations] failed:", err);
  process.exit(1);
});