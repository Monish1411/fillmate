import "server-only";
import { getSql } from "@/lib/db/client";
import { uuid } from "@/lib/utils/id";
import type { NotificationRow, NotificationType } from "@/types/activity";

/**
 * Notification centre.
 *
 * Notifications are persisted (so they survive across devices) and delivered
 * to the browser over SSE. Delivery preferences are applied at write time so
 * users are never notified about something they opted out of.
 */

export interface NotificationInput {
  userId: string;
  hostelId?: string | null;
  roomId?: string | null;
  type: NotificationType;
  title: string;
  body?: string | null;
  activityId?: string | null;
  /** Respects the user's notification preferences for this category. */
  category?: "refills" | "rotation" | "reviews" | "weekly";
}

const PREFERENCE_COLUMN: Record<NonNullable<NotificationInput["category"]>, string> = {
  refills: "notify_refills",
  rotation: "notify_rotation",
  reviews: "notify_reviews",
  weekly: "notify_weekly",
};

export async function notify(input: NotificationInput): Promise<void> {
  const sql = await getSql();

  if (input.category) {
    const column = PREFERENCE_COLUMN[input.category];
    const pref = await sql.query<Record<string, number>>(
      `SELECT "${column}" AS "pref" FROM "users" WHERE "id" = ? LIMIT 1`,
      [input.userId],
    );
    if (Number(pref[0]?.pref ?? 1) === 0) return;
  }

  // Collapse duplicates generated by the same trigger within a short window.
  const recent = await sql.query<{ id: string }>(
    `SELECT "id" FROM "notifications"
      WHERE "user_id" = ? AND "type" = ?
        AND COALESCE("activity_id", '') = COALESCE(?, '')
        AND "created_at" > ?
      LIMIT 1`,
    [
      input.userId,
      input.type,
      input.activityId ?? null,
      new Date(Date.now() - 60 * 60_000).toISOString(),
    ],
  );
  if (recent[0]) return;

  await sql.execute(
    `INSERT INTO "notifications"
       ("id", "user_id", "hostel_id", "room_id", "type", "title", "body", "activity_id", "created_at")
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`,
    [
      uuid(),
      input.userId,
      input.hostelId ?? null,
      input.roomId ?? null,
      input.type,
      input.title,
      input.body ?? null,
      input.activityId ?? null,
      new Date().toISOString(),
    ],
  );
}

/** Fan out to every member of a room, optionally skipping the actor. */
export async function notifyRoom(
  roomId: string,
  hostelId: string,
  input: Omit<NotificationInput, "userId" | "roomId" | "hostelId">,
  options: { excludeUserId?: string } = {},
): Promise<void> {
  const sql = await getSql();
  const members = await sql.query<{ user_id: string }>(
    `SELECT "user_id" FROM "room_members" WHERE "room_id" = ?`,
    [roomId],
  );
  const targets = members
    .map((m) => m.user_id)
    .filter((id) => id !== options.excludeUserId);
  await Promise.allSettled(
    targets.map((userId) =>
      notify({ ...input, userId, hostelId, roomId }),
    ),
  );
}

/** Fan out to every administrator of a hostel. */
export async function notifyAdmins(
  hostelId: string,
  input: Omit<NotificationInput, "userId" | "hostelId">,
): Promise<void> {
  const sql = await getSql();
  const admins = await sql.query<{ id: string }>(
    `SELECT "id" FROM "users" WHERE "hostel_id" = ? AND "role" IN ('hostel_admin','super_admin')`,
    [hostelId],
  );
  await Promise.allSettled(
    admins.map(({ id }) => notify({ ...input, userId: id, hostelId })),
  );
}

export async function listNotifications(
  userId: string,
  options: { limit?: number; unreadOnly?: boolean } = {},
): Promise<{ items: NotificationRow[]; unread: number }> {
  const sql = await getSql();
  const items = await sql.query<NotificationRow>(
    `SELECT * FROM "notifications"
      WHERE "user_id" = ? ${options.unreadOnly ? `AND "read_at" IS NULL` : ""}
      ORDER BY "created_at" DESC LIMIT ?`,
    [userId, options.limit ?? 40],
  );
  const unreadRows = await sql.query<{ total: number }>(
    `SELECT COUNT(*) AS "total" FROM "notifications" WHERE "user_id" = ? AND "read_at" IS NULL`,
    [userId],
  );
  return { items, unread: Number(unreadRows[0]?.total ?? 0) };
}

export async function markRead(userId: string, ids: string[]): Promise<number> {
  const sql = await getSql();
  if (ids.length === 0) return 0;
  const now = new Date().toISOString();
  return sql.execute(
    `UPDATE "notifications" SET "read_at" = ? WHERE "user_id" = ? AND "read_at" IS NULL AND "id" IN (${ids
      .map(() => "?")
      .join(",")})`,
    [now, userId, ...ids],
  );
}

export async function markAllRead(userId: string): Promise<number> {
  const sql = await getSql();
  return sql.execute(
    `UPDATE "notifications" SET "read_at" = ? WHERE "user_id" = ? AND "read_at" IS NULL`,
    [new Date().toISOString(), userId],
  );
}

export async function countUnread(userId: string): Promise<number> {
  const sql = await getSql();
  const rows = await sql.query<{ total: number }>(
    `SELECT COUNT(*) AS "total" FROM "notifications" WHERE "user_id" = ? AND "read_at" IS NULL`,
    [userId],
  );
  return Number(rows[0]?.total ?? 0);
}